bool wledAesAccept(JsonDocument& doc, bool applyState) {
  JsonObject root = doc.as<JsonObject>();
  if (root.isNull()) return false;

  if (isTransmitter() && applyState) {
    const char* b64 = root[F("aes")].as<const char*>();
    if (!queueAirFrame(b64)) return false;
    doc.clear();
    doc[F("v")] = true;
    return true;
  }

  if (!isTransmitter() && inputRaw.load() == 1 && applyState) {
    if (root.size() == 1 && (!root[F("v")].isNull() || !root[F("lv")].isNull())) return true;
    doc.clear();
    doc[F("v")] = true;
    return true;
  }

  if (!aesReady) return true;
  if (root.size() == 1 && (!root[F("v")].isNull() || !root[F("lv")].isNull())) return true;

  const char* b64 = root[F("aes")].as<const char*>();
  if (!b64) return false;
  static uint8_t plain[4096];
  size_t plainLen = 0;
  if (!decryptBase64(b64, plain, sizeof(plain), &plainLen) || plainLen == 0) return false;
  return !deserializeJson(doc, plain, plainLen);
}

bool wledAesAllowHttp(const String& url, const char* headerB64) {
  if (!aesReady) return true;
  if (!headerB64 || !headerB64[0]) return false;
  uint8_t plain[292];
  size_t plainLen = 0;
  if (!decryptBase64(headerB64, plain, sizeof(plain) - 1, &plainLen)) return false;
  plain[plainLen] = 0;
  if (plainLen != url.length()) return false;
  return memcmp(plain, url.c_str(), plainLen) == 0;
}
