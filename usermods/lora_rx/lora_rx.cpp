class LoRaRxUsermod : public Usermod {
 public:
  void setup() override {
    ensureAesLock();
    loadKeyFromFile();
    initOled();
    refreshOled(true);
    if (!spiBusReady()) {
      DEBUG_PRINTLN(F("LoRa: SPI pins are not available"));
      return;
    }
    if (!claimRadioPin(LORA_CS, true) || !claimRadioPin(LORA_RST, true) || !claimRadioPin(LORA_DIO0, false)) return;
    // DIO1 and DIO2 stay wired to the SX1276 even when RadioLib does not use them.
    if (!claimRadioPin(LORA_DIO1, false) || !claimRadioPin(LORA_DIO2, false)) return;

    SPI.begin(LORA_SCK, LORA_MISO, LORA_MOSI, LORA_CS);
    radio = new SX1276(new Module(LORA_CS, LORA_DIO0, LORA_RST, RADIOLIB_NC));
    if (!radio) return;

    const int16_t state = radio->begin(LORA_FREQ);
    if (state != RADIOLIB_ERR_NONE) {
      DEBUG_PRINTF_P(PSTR("LoRa: SX1276 begin failed (%d)\n"), state);
      return;
    }

    rxReady = xSemaphoreCreateBinary();
    txReady = xSemaphoreCreateBinary();
    if (!rxReady || !txReady) return;

    radio->setPacketReceivedAction(onDio0);
    if (listenLoRa() && radio->startReceive() == RADIOLIB_ERR_NONE) rxListening = true;

    if (xTaskCreatePinnedToCore(rxTaskFn, "lora_rx", kTaskStackBytes, nullptr, kTaskPriority, &rxTask, kTaskCore) != pdPASS) {
      DEBUG_PRINTLN(F("LoRa: task was not created"));
      return;
    }
    radioReady.store(true);
    refreshOled(true);
    DEBUG_PRINTF_P(PSTR("LoRa: listening at %.1f MHz\n"), (double)LORA_FREQ);
  }

  void loop() override {
    static uint32_t lastPaint = 0;
    const uint32_t now = millis();
    const uint32_t period = isTransmitter() ? 200 : 1000;
    if ((uint32_t)(now - lastPaint) < period) return;
    lastPaint = now;
    refreshOled(false);
  }

  void connected() override {
    refreshOled(true);
  }

  void onUpdateBegin(bool init) override {
    if (!rxTask) return;
    if (init) vTaskSuspend(rxTask);
    else vTaskResume(rxTask);
  }

  void addToJsonInfo(JsonObject& root) override {
    JsonObject user = root["u"];
    if (user.isNull()) user = root.createNestedObject("u");
    JsonArray status = user.createNestedArray(F("LoRa"));
    if (!radioReady.load()) {
      status.add(F("off"));
    } else if (isTransmitter()) {
      status.add(F("tx"));
      status.add(packetsSent.load());
    } else {
      status.add(inputRaw.load() == 0 ? F("wifi") : F("rx"));
      status.add(packetsApplied.load());
      status.add(lastRssi.load());
    }
    JsonArray aes = user.createNestedArray(F("AES-128"));
    aes.add(aesReady ? F("on") : F("set key"));
    root[F("aes128")] = aesReady;
  }

  void appendConfigData(Print& settingsScript) override {
    settingsScript.print(F("addInfo('lora_rx:aes_key',1,'32 hex. Blank keeps the current key.');"));
    settingsScript.print(F("addInfo('lora_rx:aes_unlock',1,'Current key. Required only to replace it.');"));
    settingsScript.print(F("addInfo('lora_rx:lora_role',1,'tx reenvia la trama WiFi por LoRa. rx aplica a la tira.');"));
    settingsScript.print(F("addInfo('lora_rx:rx_input',1,'Canal del receptor. Se ignora si el rol es tx.');"));
    settingsScript.print(F("var ak=d.getElementsByName('lora_rx:aes_key'); if(ak[1]){ak[1].type='password'; ak[1].maxLength=32;}"));
    settingsScript.print(F("var au=d.getElementsByName('lora_rx:aes_unlock'); if(au[1]){au[1].type='password'; au[1].maxLength=32;}"));
    settingsScript.print(F("function loraSel(n,opts){var a=d.getElementsByName(n); if(!a.length)return; var inp=a[a.length-1]; var sel=document.createElement('select'); sel.name=n; var cur=inp.value; for(var i=0;i<opts.length;i++){var op=document.createElement('option'); op.value=opts[i][0]; op.text=opts[i][1]; if(opts[i][0]===cur) op.selected=true; sel.appendChild(op);} inp.parentElement.replaceChild(sel, inp);}"));
    settingsScript.print(F("loraSel('lora_rx:lora_role',[['rx','Receptor'],['tx','Transmisor']]);"));
    settingsScript.print(F("loraSel('lora_rx:rx_input',[['lora','LoRa'],['wifi','WiFi']]);"));
  }

  void addToConfig(JsonObject& obj) override {
    JsonObject top = obj.createNestedObject(F("lora_rx"));
    // Never write the secret back into cfg.json. The key lives in /aes128.key.
    top[F("aes_key")] = "";
    top[F("aes_unlock")] = "";
    top[F("lora_role")] = isTransmitter() ? "tx" : "rx";
    top[F("rx_input")] = inputRaw.load() == 0 ? "wifi" : "lora";
  }

  bool readFromConfig(JsonObject& obj) override {
    JsonObject top = obj[F("lora_rx")];
    if (top.isNull()) return false;
    const char* role = top[F("lora_role")] | "rx";
    const char* input = top[F("rx_input")] | "lora";
    roleRaw.store(strcmp(role, "tx") == 0 ? 1 : 0);
    inputRaw.store(strcmp(input, "wifi") == 0 ? 0 : 1);
    const char* nextKey = top[F("aes_key")] | "";
    const char* unlock = top[F("aes_unlock")] | "";
    if (!nextKey[0]) return true;

    uint8_t parsed[16];
    if (!parseHexKey(nextKey, parsed)) return true;
    lockAes();
    const bool have = aesReady;
    uint8_t current[16];
    if (have) memcpy(current, aesKey, 16);
    unlockAes();
    if (have) {
      uint8_t presented[16];
      if (!parseHexKey(unlock, presented) || !keysEqual(presented, current)) return true;
    }
    storeKeyHex(nextKey);
    return true;
  }

  uint16_t getId() override { return USERMOD_ID_LORA; }
};

